class PostPreviewTokenView(APIView):
    """
    GET /api/posts/<slug>/preview-token/ -- Editors/Admins only. Issues a
    5-minute signed token for exactly this post's slug, which the public
    PostDetailView accepts (see _has_valid_preview_token) to show a draft to
    the admin's anonymous Preview-modal iframe without exposing it publicly.
    """
    permission_classes = [permissions.IsAuthenticated]

    def get(self, request, slug):
        if not request.user.has_permission('manage_posts'):
            raise PermissionDenied('Only Editors and Admins can preview posts.')
        get_object_or_404(Post, slug=slug)
        token = signing.dumps({'slug': slug}, salt='post-preview')
        return Response({'token': token})
